// Dumps per-block-state light properties from the vanilla jar into src/gen/light_data.hpp.
// Run through tools/gen_light_data.py (builds the classpath). Tool-time only: the server never runs vanilla code.
//
// Per state: light emission, light dampening, and (when the state uses its shape for light occlusion) the 6
// face occlusion shapes, as ids into a table of distinct face shapes. FACE_OCCLUDES[a][b] is vanilla's
// Shapes.faceShapeOccludes(a, b), evaluated here so the C++ side needs no voxel shape code.
import java.io.PrintWriter;
import java.util.*;
import net.minecraft.SharedConstants;
import net.minecraft.core.Direction;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

public class LightDump {
    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        int n = Block.BLOCK_STATE_REGISTRY.size();
        List<VoxelShape> shapes = new ArrayList<>();
        Map<String, Integer> shapeIds = new HashMap<>();
        shapes.add(Shapes.empty());
        shapeIds.put("", 0);
        List<String> tuples = new ArrayList<>();
        Map<String, Integer> tupleIds = new HashMap<>();
        tuples.add("");  // 0 = isEmptyShape (no shape-based occlusion)
        tupleIds.put("", 0);
        int[] props = new int[n];
        for (int id = 0; id < n; id++) {
            BlockState s = Block.BLOCK_STATE_REGISTRY.byId(id);
            int tuple = 0;
            if (s.canOcclude() && s.useShapeForLightOcclusion()) {
                StringBuilder key = new StringBuilder();
                for (Direction d : Direction.values()) {  // DOWN UP NORTH SOUTH WEST EAST
                    VoxelShape f = s.getFaceOcclusionShape(d);
                    String k = f.isEmpty() ? "" : (f == Shapes.block() ? "B" : "") + f.toAabbs().toString();
                    Integer sid = shapeIds.get(k);
                    if (sid == null) {
                        sid = shapes.size();
                        shapes.add(f);
                        shapeIds.put(k, sid);
                    }
                    key.append(sid).append(',');
                }
                String k = key.toString();
                Integer tid = tupleIds.get(k);
                if (tid == null) {
                    tid = tuples.size();
                    tuples.add(k);
                    tupleIds.put(k, tid);
                }
                tuple = tid;
            }
            if (tuple > 255 || s.getLightEmission() > 15 || s.getLightDampening() > 15) throw new IllegalStateException("table overflow at " + id);
            props[id] = s.getLightEmission() | s.getLightDampening() << 4 | tuple << 8;
        }
        try (PrintWriter w = new PrintWriter(args[0])) {
            w.println("// Generated by tools/gen_light_data.py from the vanilla 26.3 jar. Do not edit.");
            w.println("#pragma once");
            w.println("#include <cstdint>");
            w.println("namespace light_data {");
            w.println("// bits 0-3 light emission, 4-7 light dampening, 8-15 face tuple (0 = isEmptyShape)");
            w.print("inline constexpr uint16_t PROPS[" + n + "] = {");
            for (int i = 0; i < n; i++) w.print((i % 32 == 0 ? "\n" : "") + props[i] + ",");
            w.println("};");
            w.println("// face shape id per direction (DOWN UP NORTH SOUTH WEST EAST); 0 = empty");
            w.println("inline constexpr uint8_t FACES[" + tuples.size() + "][6] = {");
            w.println("{0,0,0,0,0,0},");
            for (int t = 1; t < tuples.size(); t++) w.println("{" + tuples.get(t) + "},");
            w.println("};");
            int m = shapes.size();
            w.println("inline constexpr int SHAPES = " + m + ";");
            w.println("// Shapes.faceShapeOccludes(a, b)");
            w.println("inline constexpr bool FACE_OCCLUDES[" + m + "][" + m + "] = {");
            for (int a = 0; a < m; a++) {
                StringBuilder row = new StringBuilder("{");
                for (int b = 0; b < m; b++) row.append(Shapes.faceShapeOccludes(shapes.get(a), shapes.get(b)) ? "1," : "0,");
                w.println(row.append("},"));
            }
            w.println("};");
            w.println("}  // namespace light_data");
        }
        System.out.println(n + " states, " + tuples.size() + " face tuples, " + shapes.size() + " face shapes");
    }
}
