#!/usr/bin/env python3
"""Generate src/worldgen/biome_params.inc from the vanilla biome_parameters report.

The report stores unquantizeCoord(q) = (float)q / 10000f. We recover the exact original
long q (the one OverworldBiomeBuilder produced via quantizeCoord) by inverting that
division, NOT by re-quantizing, since (long)(f*10000f) can truncate to q-1."""
import json, sys, numpy as np
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = ROOT / "vanilla/generated/reports/biome_parameters/minecraft" / (sys.argv[1] if len(sys.argv) > 1 else "overworld.json")
out = ROOT / "src/worldgen/biome_params.inc"
DIMS = ["temperature", "humidity", "continentalness", "erosion", "depth", "weirdness"]
requant_diff = 0

def unq(s):
    global requant_diff
    f = np.float32(s)
    q = int(round(float(f) * 10000))
    assert np.float32(q) / np.float32(10000) == f, (s, q)
    if int(f * np.float32(10000)) != q: requant_diff += 1
    return q

rows = []
for e in json.loads(src.read_text())["biomes"]:
    p = e["parameters"]
    vals = []
    for d in DIMS:
        v = p[d] if isinstance(p[d], list) else [p[d], p[d]]
        vals += [unq(repr(v[0])), unq(repr(v[1]))]
    vals.append(unq(repr(p["offset"])))
    rows.append(f"{{biomes::{e['biome'].split(':')[1]}, {{{', '.join(map(str, vals))}}}}},")
out.write_text(f"// Generated by tools/gen_biome_params.py from {src.relative_to(ROOT)} -- do not edit.\n"
               "// {biome, {tmin,tmax, hmin,hmax, cmin,cmax, emin,emax, dmin,dmax, wmin,wmax, offset}}\n"
               + "\n".join(rows) + "\n")
print(f"{len(rows)} entries -> {out} ({requant_diff} values where naive re-quantize would differ)")
