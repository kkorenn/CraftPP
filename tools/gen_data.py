#!/usr/bin/env python3
"""Turns the vanilla server jar's data + generator reports into files CraftPP uses.

Prereq (see README): vanilla/src/data (extracted jar data) and vanilla/generated/reports.
Outputs:
  data/config.bin    - framed configuration-phase packets (registry_data x N, update_tags)
  src/gen/ids.hpp    - packet ids, block state ids, registry entry ids
"""
import json, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VAN = os.path.join(ROOT, "vanilla")
DATA = os.path.join(VAN, "src", "data", "minecraft")
REPORTS = os.path.join(VAN, "generated", "reports")

# Order of RegistryDataLoader.SYNCHRONIZED_REGISTRIES (26.3).
SYNCED = ("worldgen/biome chat_type trim_pattern trim_material wolf_variant wolf_sound_variant pig_variant "
          "pig_sound_variant frog_variant cat_variant cat_sound_variant cow_sound_variant cow_variant "
          "chicken_sound_variant chicken_variant zombie_nautilus_variant painting_variant sulfur_cube_archetype "
          "dimension_type damage_type banner_pattern enchantment jukebox_song instrument test_environment "
          "test_instance dialog world_clock timeline decorated_pot_pattern block_transformer "
          "worldgen/block_state_provider").split()


def varint(n):
    n &= 0xFFFFFFFF
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        out.append(b | (0x80 if n else 0))
        if not n:
            return bytes(out)


def string(s):
    b = s.encode()
    return varint(len(b)) + b


def frame(body):
    return varint(len(body)) + body


def json_ids(folder):
    """Entry ids of a data-driven registry folder, sorted (our numeric ids = this order)."""
    base = os.path.join(DATA, folder)
    ids = []
    for dirpath, _, files in os.walk(base):
        for f in files:
            if f.endswith(".json"):
                rel = os.path.relpath(os.path.join(dirpath, f), base)[:-5]
                ids.append("minecraft:" + rel.replace(os.sep, "/"))
    return sorted(ids)


packets = json.load(open(os.path.join(REPORTS, "packets.json")))
registries = json.load(open(os.path.join(REPORTS, "registries.json")))
blocks = json.load(open(os.path.join(REPORTS, "blocks.json")))

cfg = {k.split(":")[1]: v["protocol_id"] for k, v in packets["configuration"]["clientbound"].items()}

# registry name -> {entry id -> numeric id}
id_maps = {}
out = bytearray()
for reg in SYNCED:
    ids = json_ids(reg)
    id_maps["minecraft:" + reg] = {e: i for i, e in enumerate(ids)}
    body = varint(cfg["registry_data"]) + string("minecraft:" + reg) + varint(len(ids))
    for e in ids:
        body += string(e) + b"\x00"  # no NBT: client has it via the known "minecraft:core" pack
    out += frame(body)
for reg, v in registries.items():
    id_maps.setdefault(reg, {e: d["protocol_id"] for e, d in v["entries"].items()})

# Tags: resolve nested "#tag" references to flat numeric id lists.
tags_by_reg = {}
tag_root = os.path.join(DATA, "tags")
for dirpath, _, files in os.walk(tag_root):
    for f in files:
        if not f.endswith(".json"):
            continue
        rel = os.path.relpath(os.path.join(dirpath, f), tag_root)[:-5].replace(os.sep, "/")
        # registry folder can be nested (worldgen/biome); find longest prefix that is a known registry
        parts = rel.split("/")
        for cut in range(len(parts) - 1, 0, -1):
            reg = "minecraft:" + "/".join(parts[:cut])
            if reg in id_maps:
                tags_by_reg.setdefault(reg, {})["minecraft:" + "/".join(parts[cut:])] = \
                    json.load(open(os.path.join(dirpath, f)))["values"]
                break


def resolve(reg, tag, seen):
    if tag in seen:
        return seen[tag]
    seen[tag] = []
    res = []
    for v in tags_by_reg[reg].get(tag, []):
        vid = v["id"] if isinstance(v, dict) else v
        if vid.startswith("#"):
            res += resolve(reg, vid[1:], seen)
        elif vid in id_maps[reg]:
            res.append(id_maps[reg][vid])
    seen[tag] = list(dict.fromkeys(res))
    return seen[tag]


body = varint(cfg["update_tags"]) + varint(len(tags_by_reg))
for reg, tags in sorted(tags_by_reg.items()):
    seen = {}
    body += string(reg) + varint(len(tags))
    for tag in sorted(tags):
        ids = resolve(reg, tag, seen)
        body += string(tag) + varint(len(ids)) + b"".join(varint(i) for i in ids)
out += frame(body)

os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
open(os.path.join(ROOT, "data", "config.bin"), "wb").write(out)

# ---- C++ header ----
KEYWORDS = {"bool", "float", "double", "int", "long", "char", "short", "string", "time"}
def ident(s):
    s = re.sub(r"[^a-z0-9_]", "_", s.split(":")[-1])
    return s + "_" if s in KEYWORDS else s
h = ["// Generated by tools/gen_data.py from the vanilla 26.3 jar. Do not edit.", "#pragma once", "#include <cstdint>", ""]
version = json.load(open(os.path.join(VAN, "src", "version.json")))
h += [f'inline constexpr int PROTOCOL_VERSION = {version["protocol_version"]};',
      f'inline constexpr const char* GAME_VERSION = "{version["id"]}";',
      f'inline constexpr int DATA_VERSION = {version["world_version"]};  // SharedConstants.WORLD_VERSION (save files)', ""]
for state, short in [("login", "login"), ("configuration", "config"), ("play", "play")]:
    for d, s in [("clientbound", "cb"), ("serverbound", "sb")]:
        h.append(f"namespace {short}_{s} {{")
        for k, v in packets[state][d].items():
            h.append(f"inline constexpr int {ident(k.replace('/', '_'))} = {v['protocol_id']};")
        h.append("}")
total = 0
h.append("namespace blocks {")
for name, b in blocks.items():
    for st in b["states"]:
        total = max(total, st["id"] + 1)
        if st.get("default"):
            h.append(f"inline constexpr int {ident(name)} = {st['id']};")
h += ["}", f"inline constexpr int BLOCK_STATE_COUNT = {total};"]
# States with a non-empty FluidState (LevelChunkSection fluidCount) and air states (BlockState.isAir).
ALWAYS_WATER = {"minecraft:water", "minecraft:lava", "minecraft:bubble_column", "minecraft:kelp",
                "minecraft:kelp_plant", "minecraft:seagrass", "minecraft:tall_seagrass"}
fluid = sorted(st["id"] for name, b in blocks.items() for st in b["states"]
               if name in ALWAYS_WATER or st.get("properties", {}).get("waterlogged") == "true")
air = sorted(st["id"] for name, b in blocks.items() for st in b["states"]
             if name in ("minecraft:air", "minecraft:cave_air", "minecraft:void_air"))
h.append("inline constexpr int32_t FLUID_STATES[] = {" + ",".join(map(str, fluid)) + "};")
h.append("inline constexpr int32_t AIR_STATES[] = {" + ",".join(map(str, air)) + "};")
for reg, ns in [("minecraft:worldgen/biome", "biomes"), ("minecraft:dimension_type", "dimension_types")]:
    h.append(f"namespace {ns} {{")
    for e, i in id_maps[reg].items():
        h.append(f"inline constexpr int {ident(e)} = {i};")
    h.append(f"inline constexpr int COUNT = {len(id_maps[reg])};")
    h.append("inline constexpr const char* NAMES[] = {" + ",".join(f'"{e}"' for e, _ in sorted(id_maps[reg].items(), key=lambda kv: kv[1])) + "};")
    h.append("}")
for reg, ns in [("minecraft:entity_type", "entity_types"), ("minecraft:command_argument_type", "arg_types"),
                ("minecraft:block_entity_type", "block_entity_types")]:
    h.append(f"namespace {ns} {{")
    for e, i in id_maps[reg].items():
        h.append(f"inline constexpr int {ident(e)} = {i};")
    if ns != "arg_types":  # registry names by id (world storage: block entity / entity ids)
        h.append("inline constexpr const char* NAMES[] = {" + ",".join(f'"{e}"' for e, _ in sorted(id_maps[reg].items(), key=lambda kv: kv[1])) + "};")
    h.append("}")
# item id -> default block state it places (-1 = not a block item). Same-name rule covers most blocks.
# Items named differently from their block (redstone, string, seeds, berries...) come from Items.java's
# createBlockItemWithCustomItemName(Blocks.X) registrations.
default_state = {name: st["id"] for name, b in blocks.items() for st in b["states"] if st.get("default")}
items = sorted(id_maps["minecraft:item"].items(), key=lambda kv: kv[1])
items_java = open(os.path.join(ROOT, "vanilla/src/net/minecraft/world/item/Items.java")).read()
custom = {"minecraft:" + m.group(1).lower(): "minecraft:" + m.group(2).lower() for m in re.finditer(
    r"Item (\w+) = registerItem\(\s*BlockItemIds\.\w+,\s*createBlockItemWithCustomItemName\(Blocks\.(\w+)\)", items_java)}
assert all(i in id_maps["minecraft:item"] and b in default_state for i, b in custom.items()), custom
h.append("inline constexpr int32_t ITEM_TO_BLOCK[] = {" +
         ",".join(str(default_state.get(custom.get(name, name), -1)) if name != "minecraft:air" else "-1" for name, _ in items) + "};")
h.append(f"inline constexpr int ITEM_COUNT = {len(items)};")
# Block -> clone item (pick block): states are contiguous per block, so store each block's first state id.
# ponytail: same-name rule only; wall_torch->torch, redstone_wire->redstone etc. need overrides.
item_id = dict(items)
pairs = sorted((min(st["id"] for st in b["states"]), item_id.get(name, -1) if name != "minecraft:air" else -1)
               for name, b in blocks.items())
firsts, picks = [str(f) for f, _ in pairs], [str(i) for _, i in pairs]
h.append("inline constexpr int32_t BLOCK_FIRST_STATE[] = {" + ",".join(firsts) + "};")
h.append("inline constexpr int16_t BLOCK_PICK_ITEM[] = {" + ",".join(picks) + "};")
os.makedirs(os.path.join(ROOT, "src", "gen"), exist_ok=True)
open(os.path.join(ROOT, "src", "gen", "ids.hpp"), "w").write("\n".join(h) + "\n")
print(f"config.bin {len(out)} bytes, {len(SYNCED)} registries, {sum(map(len, tags_by_reg.values()))} tags, "
      f"{total} block states")

# Survival data (blocks/items/loot/recipes) -> data/game.json
exec(open(os.path.join(ROOT, "tools", "gen_game_data.py")).read(), {"__name__": "__main__", "__file__": os.path.join(ROOT, "tools", "gen_game_data.py")})
